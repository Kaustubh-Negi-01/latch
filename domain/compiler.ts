import { ScenarioPlanSchema, type ScenarioPlan, type Variant } from './model';
import { getScenario } from './manifest';
import { getScenarioProgram } from './program';
import { runRaceProtocol } from './protocol.js';

export interface CompileOptions { baseURL?: string; variant?: Variant }

/** Compile only a validated finite plan. Narration never becomes source code. */
export function compilePlaywrightSpec(input: ScenarioPlan, options: CompileOptions = {}): string {
  const plan = ScenarioPlanSchema.parse(input);
  const scenario = getScenario(plan.scenarioId);
  const program = getScenarioProgram(plan.scenarioId);
  const variant = options.variant ?? 'fixed';
  if (variant !== 'fixed' && variant !== 'buggy') throw new Error('Unknown fixture variant.');
  const baseURL = options.baseURL ?? 'http://127.0.0.1:4173';
  const url = new URL(baseURL);
  if (!['http:', 'https:'].includes(url.protocol)) throw new Error('The fixture base URL must use HTTP or HTTPS.');
  const literal = (value: unknown) => JSON.stringify(value, null, 2).replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');
  return `// Generated by Latch. Fixture data is synthetic; no timing sleeps are used.
// Run: npx playwright test
// Set LATCH_BASE_URL to your running Latch server; LATCH_VARIANT=buggy reproduces the failure.
import { test, expect } from '@playwright/test';

const program = ${literal(program)};
const order = ${literal(plan.order)};
const baseURL = process.env.LATCH_BASE_URL || ${literal(baseURL)};
const variant = process.env.LATCH_VARIANT || ${literal(variant)};
// tsx/esbuild can preserve internal function names with this harmless helper.
const __name = (value, name) => Object.defineProperty(value, 'name', { value: name, configurable: true });

const runRaceProtocol = ${runRaceProtocol.toString()};

test(${literal(`${scenario.shortLabel} — ${scenario.expectedInvariant}`)}, async ({ page }) => {
  test.setTimeout(30000);
  await runRaceProtocol(page, program, order, variant, baseURL);
  // Final DOM assertion runs only after both request handlers have settled.
  await expect(page.getByTestId(program.assertion.testId)).toHaveAttribute(
    program.assertion.attribute,
    program.assertion.expected,
  );
});
`;
}
